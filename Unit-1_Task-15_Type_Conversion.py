a = "10"
b = "20.5"

# String to Integer
x = int(a)
print("String to Integer:", x)
print(type(x))

# String to Float
y = float(b)
print("String to Float:", y)
print(type(y))

# Integer to Float
z = float(x)
print("Integer to Float:", z)
print(type(z))

# Integer to String
s = str(x)
print("Integer to String:", s)
print(type(s))